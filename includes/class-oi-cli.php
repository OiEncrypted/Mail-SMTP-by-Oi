<?php
/**
 * WP-CLI Commands for Mail SMTP by Oi
 *
 * Provides command-line management for SMTP status, test email delivery,
 * email log inspection, and background queue handling.
 *
 * @package Mail_SMTP_By_Oi
 */

defined('ABSPATH') || exit;

if (!defined('WP_CLI') || !WP_CLI) {
    return;
}

class OI_CLI {

    /**
     * Show current Mail SMTP configuration and delivery health.
     *
     * ## EXAMPLES
     *
     *     wp oi-smtp status
     *
     * @subcommand status
     */
    public function status($args, $assoc_args) {
        $settings = OI_Options::get_all(false);
        $stats    = OI_Logger::get_stats();
        $q_stats  = OI_Queue::get_stats();

        WP_CLI::line(WP_CLI::colorize('%B--- Mail SMTP by Oi System Status ---%n'));
        WP_CLI::line('Enabled:          ' . (!empty($settings['enabled']) ? WP_CLI::colorize('%GYes%n') : WP_CLI::colorize('%RNo%n')));
        WP_CLI::line('Active Mailer:    ' . WP_CLI::colorize('%C' . esc_html($settings['mailer'] ?? 'smtp') . '%n'));
        WP_CLI::line('From Email:       ' . esc_html($settings['from_email'] ?? ''));
        WP_CLI::line('From Name:        ' . esc_html($settings['from_name'] ?? ''));
        WP_CLI::line('Fallback Mailer:  ' . (!empty($settings['enable_fallback']) ? esc_html($settings['fallback_mailer']) : 'Disabled'));
        WP_CLI::line('Email Logging:    ' . (!empty($settings['enable_logging']) ? 'Enabled (' . (int)$settings['log_retention_days'] . ' days retention)' : 'Disabled'));
        WP_CLI::line('Background Queue: ' . (!empty($settings['enable_queue']) ? WP_CLI::colorize('%GActive%n') : 'Disabled'));
        WP_CLI::line('');

        WP_CLI::line(WP_CLI::colorize('%B--- Delivery Statistics ---%n'));
        WP_CLI::line('Total Logs:       ' . (int)$stats['total']);
        WP_CLI::line('Successful:       ' . WP_CLI::colorize('%G' . (int)$stats['sent'] . '%n'));
        WP_CLI::line('Failed:           ' . WP_CLI::colorize('%R' . (int)$stats['failed'] . '%n'));
        WP_CLI::line('Queue Pending:    ' . (int)$q_stats['pending']);
        WP_CLI::line('Queue Failed:     ' . (int)$q_stats['failed']);
    }

    /**
     * Send a test email from the command line with diagnostic handshake.
     *
     * ## OPTIONS
     *
     * [--to=<email>]
     * : Recipient email address (defaults to admin_email).
     *
     * [--subject=<subject>]
     * : Custom subject for the test email.
     *
     * ## EXAMPLES
     *
     *     wp oi-smtp test --to=developer@example.com
     *     wp oi-smtp test --to=admin@example.com --subject="Production Mail Test"
     *
     * @subcommand test
     */
    public function test($args, $assoc_args) {
        $to      = isset($assoc_args['to']) ? sanitize_email($assoc_args['to']) : get_option('admin_email');
        $subject = isset($assoc_args['subject']) ? sanitize_text_field($assoc_args['subject']) : sprintf(__('Mail SMTP by Oi - CLI Test Email [%s]', 'mail-smtp-by-oi'), date_i18n('Y-m-d H:i:s'));

        if (!is_email($to)) {
            WP_CLI::error(sprintf('Invalid recipient email address: %s', $to));
        }

        WP_CLI::line(sprintf('Dispatching test email to: %s ...', $to));

        $settings = OI_Options::get_all(true);
        $mailer_key = $settings['mailer'] ?? 'smtp';

        $body = "Congratulations!\n\nThis is a diagnostic test email generated by Mail SMTP by Oi via WP-CLI.\n\n"
              . "Site: " . home_url() . "\n"
              . "Active Mailer: " . strtoupper($mailer_key) . "\n"
              . "Time: " . current_time('mysql') . "\n\n"
              . "If you received this message, your WordPress outbound email subsystem is functioning correctly!";

        $headers = [
            'Content-Type: text/plain; charset=UTF-8',
            'X-Mailer: Mail-SMTP-by-Oi-CLI',
        ];

        $result = wp_mail($to, $subject, $body, $headers);

        if ($result) {
            WP_CLI::success(sprintf('Test email successfully sent to %s via %s!', $to, strtoupper($mailer_key)));
        } else {
            WP_CLI::error(sprintf('Failed to send test email to %s. Inspect log via "wp oi-smtp logs" for details.', $to));
        }
    }

    /**
     * View recent email logs.
     *
     * ## OPTIONS
     *
     * [--limit=<num>]
     * : Number of log records to fetch. Default: 10.
     *
     * [--status=<status>]
     * : Filter by status: 'sent', 'failed', or 'all'. Default: 'all'.
     *
     * ## EXAMPLES
     *
     *     wp oi-smtp logs --limit=20
     *     wp oi-smtp logs --status=failed
     *
     * @subcommand logs
     */
    public function logs($args, $assoc_args) {
        $limit  = isset($assoc_args['limit']) ? absint($assoc_args['limit']) : 10;
        $status = isset($assoc_args['status']) ? sanitize_key($assoc_args['status']) : 'all';

        $filter_status = ($status === 'sent' || $status === 'failed') ? $status : '';
        $logs = OI_Logger::get_logs(1, $limit, '', $filter_status);

        if (empty($logs)) {
            WP_CLI::line('No email logs found matching criteria.');
            return;
        }

        $formatted = [];
        foreach ($logs as $log) {
            $formatted[] = [
                'ID'      => $log['id'],
                'Date'    => $log['created_at'],
                'To'      => substr($log['to_email'], 0, 30),
                'Subject' => substr($log['subject'], 0, 35),
                'Mailer'  => $log['mailer'],
                'Status'  => $log['status'] === 'sent' ? WP_CLI::colorize('%Gsent%n') : WP_CLI::colorize('%Rfailed%n'),
            ];
        }

        WP_CLI\Utils\format_items('table', $formatted, ['ID', 'Date', 'To', 'Subject', 'Mailer', 'Status']);
    }

    /**
     * Manage the background email queue.
     *
     * ## OPTIONS
     *
     * [--action=<action>]
     * : Action to perform: 'status', 'flush', or 'clear'. Default: 'status'.
     *
     * ## EXAMPLES
     *
     *     wp oi-smtp queue --action=status
     *     wp oi-smtp queue --action=flush
     *     wp oi-smtp queue --action=clear
     *
     * @subcommand queue
     */
    public function queue($args, $assoc_args) {
        $action = isset($assoc_args['action']) ? sanitize_key($assoc_args['action']) : 'status';

        switch ($action) {
            case 'flush':
                WP_CLI::line('Processing pending queue items...');
                delete_transient('oi_queue_worker_lock');
                OI_Queue::process_queue();
                $stats = OI_Queue::get_stats();
                WP_CLI::success(sprintf('Queue processed. Remaining pending: %d, Failed: %d', $stats['pending'], $stats['failed']));
                break;

            case 'clear':
                WP_CLI::confirm('Are you sure you want to delete ALL pending and failed queue items?');
                global $wpdb;
                $table = OI_Queue::get_table_name();
                $wpdb->query("TRUNCATE TABLE $table");
                delete_transient('oi_queue_worker_lock');
                WP_CLI::success('Background email queue has been cleared.');
                break;

            case 'status':
            default:
                $stats = OI_Queue::get_stats();
                WP_CLI::line(WP_CLI::colorize('%B--- Background Email Queue Status ---%n'));
                WP_CLI::line('Enabled:    ' . (OI_Queue::is_enabled() ? WP_CLI::colorize('%GYes%n') : 'No'));
                WP_CLI::line('Pending:    ' . $stats['pending']);
                WP_CLI::line('Processing: ' . $stats['processing']);
                WP_CLI::line('Failed:     ' . ($stats['failed'] > 0 ? WP_CLI::colorize('%R' . $stats['failed'] . '%n') : '0'));
                break;
        }
    }
}

